// Пользовательские данные, которые нельзя переводить (amnezia-vpn-server-jany).
//
// Имя клиента — единственное, чем оператор отличает одного человека от
// другого. Машинный перевод страницы переписывает его вместе с интерфейсом:
// владелец видел test / router / Мама, пользователь на телефоне —
// тест / маршрутизатор / Ни, и подтверждение удаления показало бы ему то же
// переведённое имя.
//
// Объявленный язык страницы (index.html) убирает само предложение перевода,
// но пользователь вправе включить его руками — тогда имена обязаны остаться
// как есть. Поэтому пометка живёт на самих данных, а не только на странице.
//
// Двойная пометка намеренна: translate="no" — стандарт HTML, класс
// notranslate — то, что исторически понимает переводчик Google.
import type { ReactNode } from "react";

import { cn } from "@/lib/utils";

// Пометка для элемента, который уже существует: имя клиента в карточке живёт
// в кнопке (или в span на узком экране), несущей truncate и min-w-0, и
// оборачивать его во второй элемент значило бы уводить эти классы от текста.
export const noTranslate = { translate: "no", className: "notranslate" } as const;

export function UserText({
  children,
  className,
}: {
  children: ReactNode;
  className?: string;
}) {
  return (
    <span translate="no" className={cn("notranslate", className)}>
      {children}
    </span>
  );
}
